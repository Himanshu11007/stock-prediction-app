"""
tests/test_ranking_v1_golden.py — Ranking Engine v1.0 must not change.

tests/data/ranking_v1_golden.json was generated by running this file's
inputs through the code of the v1 freeze commit 37bd87a (ranking v1
validation and freeze), extracted with `git archive`.
Any change to FQVF, component scoring, weights, eligibility or ranking makes
this test fail. Prediction Engine v2 must never require editing this file.
"""
import json
from pathlib import Path

import pytest

from fqvf import FQVFInputs, evaluate
from ranking.service import DEFAULT_WEIGHTS, RankingInput, StockRankingService

GOLDEN = json.loads((Path(__file__).parent / "data" / "ranking_v1_golden.json").read_text(encoding="utf-8"))

ANNUAL = [{"fiscal_year_end": f"{y}-03-31", "diluted_eps": e, "net_income": e * 1e9,
           "stockholders_equity": e * 5e9, "free_cash_flow": 6e9, "operating_cash_flow": 1e10,
           "ebit": e * 2e9, "total_assets": e * 8e9, "current_liabilities": e * 1e9}
          for y, e in ((2026, 16), (2025, 14), (2024, 12), (2023, 10))]

FQVF_CASES = {
    "strong": dict(price=100, price_age_days=1, sector="S", industry="I", trailing_pe=10, price_to_book=0.8,
                   price_to_sales=1.0, debt_to_equity=0.3, dividend_yield=0.02, payout_ratio=0.3, annual=ANNUAL),
    "expensive_levered": dict(price=1400, price_age_days=1, sector="S", industry="I", trailing_pe=28,
                              price_to_book=0.8, price_to_sales=1.0, debt_to_equity=3.0, annual=ANNUAL),
    "sparse": dict(price=50, price_age_days=10, sector=None, industry=None),
}


def _tech(i):
    return {"return_60d": 0.01 * i - 0.04, "volatility_annual": 0.2 + 0.015 * i, "max_drawdown_1y": -0.1 - 0.01 * i,
            "trend_score": (i % 5 - 2) / 4, "regime_score": 0.5 - 0.1 * (i % 3), "regime": "Bullish",
            "regime_reason": "x", "avg_volume_20d": 1e6 if i != 7 else 1e4}


@pytest.fixture(scope="module")
def fqvf_results():
    return {k: evaluate(FQVFInputs(**v)).to_dict() for k, v in FQVF_CASES.items()}


@pytest.fixture(scope="module")
def ranked(fqvf_results):
    inputs = []
    for i in range(14):
        case = ("strong", "expensive_levered", "sparse")[i % 3]
        inputs.append(RankingInput(
            symbol=f"G{i:02d}.NS", name=f"G{i:02d}", sector="S", fqvf=fqvf_results[case], technical=_tech(i), ml=None,
            market_status="STALE" if i == 11 else "OK", market_age_days=9 if i == 11 else 1,
            fundamentals_status="OK" if case != "sparse" else "PARTIAL"))
    return {r["symbol"]: r for r in StockRankingService(DEFAULT_WEIGHTS).rank(inputs)}


def test_frozen_weights():
    assert DEFAULT_WEIGHTS == GOLDEN["weights"]
    assert DEFAULT_WEIGHTS == {"quality": 25, "valuation": 20, "financial_health": 15, "technical_trend": 10,
                               "momentum": 10, "risk": 10, "sector_outlook": 5, "market_regime": 5, "ml_signal": 0}


@pytest.mark.parametrize("case", sorted(FQVF_CASES))
def test_fqvf_matches_the_freeze_commit(fqvf_results, case):
    got, want = fqvf_results[case], GOLDEN["fqvf"][case]
    assert got["score"] == want["score"]
    assert got["coverage"] == want["coverage"]
    assert got["counts"] == want["counts"]
    assert [c["status"] for c in got["checks"]] == want["statuses"]          # 18 checks, statuses unchanged
    assert len(want["statuses"]) == 18


def test_scores_ranks_and_eligibility_match_the_freeze_commit(ranked):
    assert set(ranked) == set(GOLDEN["ranking"])
    for symbol, want in GOLDEN["ranking"].items():
        r = ranked[symbol]
        assert r["stockai_score"] == want["score"], symbol
        assert r["score_coverage"] == want["coverage"], symbol
        assert r["rank"] == want["rank"], symbol
        assert r["eligible"] == want["eligible"], symbol
        assert r["ineligible_reasons"] == want["ineligible_reasons"], symbol
        assert {k: (v or {}).get("score") for k, v in r["components"].items()} == want["components"], symbol


def test_golden_fixture_covers_eligible_and_ineligible_cases():
    rows = GOLDEN["ranking"].values()
    assert sum(r["eligible"] for r in rows) >= 5
    assert any(not r["eligible"] for r in rows)
