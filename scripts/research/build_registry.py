"""
scripts/research/build_registry.py — regenerate docs/ML_EXPERIMENT_REGISTRY.md.

Metrics are read from the committed result JSONs in scripts/research/output
and scripts/audit/output; conclusions and promotion decisions are the
recorded judgements in CONCLUSIONS below (each one cites its document).

Usage:
    python scripts/research/build_registry.py
"""
from __future__ import annotations

import json
import subprocess

import common

DOC = common.ROOT / "docs" / "ML_EXPERIMENT_REGISTRY.md"
OUT = common.OUTPUT
SEG = "CAL 2024-07-01→2025-03-31 · DEV 2025-04-01→2025-09-30 · FINAL 2025-10-01→2026-09-30"
PROD = "LR/RF/XGB production hyperparameters"
WEIGHTS = "0.20/0.30/0.50"

# experiment id -> (conclusion, promotion)
CONCLUSIONS: dict[str, tuple[str, str]] = {}


def load(name):
    path = OUT / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def git_head() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=common.ROOT,
                                       text=True).strip()
    except Exception:
        return "?"


def fmt_acc(m):
    if not m:
        return "—"
    ci = m.get("accuracy_ci95_date_clustered") or m.get("accuracy_ci95")
    return f"{m['accuracy'] * 100:.1f}% ({ci[0] * 100 if ci[0] <= 1 else ci[0]:.1f}–{ci[1] * 100 if ci[1] <= 1 else ci[1]:.1f})"


def entry(eid, title, *, feature_set, target, model, hyper, weights, n_stocks, n_pred,
          results, conclusion_key=None, extra="",
          training="rolling 1-year window, refit every 5 sessions, labels known at refit",
          segments=SEG):
    concl, promo = CONCLUSIONS.get(conclusion_key or eid, ("see phase document", "No"))
    return (f"### {eid} — {title}\n\n"
            f"| Field | Value |\n|---|---|\n"
            f"| Date | 2026-10-03 |\n| Code version | parent commit `{git_head()}` + this sprint's commit |\n"
            f"| Feature set | {feature_set} |\n| Target | {target} |\n| Model | {model} |\n"
            f"| Hyperparameters | {hyper} |\n| Ensemble weights | {weights} |\n"
            f"| Training | {training} |\n"
            f"| Calibration / selection / OOS | {segments} |\n"
            f"| Stocks / predictions | {n_stocks} / {n_pred} |\n"
            f"| Results | {results} |\n| Conclusion | {concl} |\n"
            f"| Production promotion | {promo} |\n{extra}\n")


def main() -> None:
    parts = [
        "# ML Experiment Registry\n",
        "Permanent research history for StockAI Pro. Generated by "
        "`scripts/research/build_registry.py` from the committed result JSONs; "
        "conclusions are recorded judgements that cite their phase document. "
        "Accuracy CIs are date-clustered bootstrap 95% intervals unless noted.\n",
        "Promotion rule (all required): temporal integrity, reproducibility, no "
        "leakage, improvement on more than one horizon or a documented objective, "
        "adequate sample, no severe calibration degradation, documentation, "
        "regression tests, and comparison with the production baseline "
        "**selected on DEV and confirmed on FINAL**.\n",
    ]
    parts.append(
        "## Summary (research sprint 2026-10-03)\n\n"
        "| ID | Question | Answer | Promote? |\n|---|---|---|---|\n"
        "| E11B | Is the production benchmark clean after the zero-volume fix? | Yes; 1D 49.9 / 3D 49.1 / 5D 51.4 / 10D 51.2%, all CIs contain 50% | Deployed (integrity fix) |\n"
        "| E-BASE | Does the production configuration discriminate? | No: AUC 0.48–0.51 everywhere | — |\n"
        "| E12 | Can confidence be calibrated? | Yes, but only to the no-skill base rate | No |\n"
        "| E13.G | Which feature groups add signal? | None reproducibly | No |\n"
        "| E13.C | Which components add signal? | None; XGBoost adds most over-confidence | No |\n"
        "| E14 | Does another model do better? | No; DEV pick failed on FINAL | No |\n"
        "| E15.T | Is another target/horizon better supported? | Not in accuracy/AUC; 10D return spread is a weak lead | No (track prospectively) |\n"
        "| E15.D | Would other thresholds/filters help? | No; DEV picks failed on FINAL, effects flip sign | No |\n"
    )
    parts.extend(SECTIONS(load))
    DOC.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {DOC}")


